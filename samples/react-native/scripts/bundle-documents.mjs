// Documents are text, not modules: bundling them as raw strings keeps the
// int and double distinction that a JSON import would collapse, and it is
// the same shape a real app receives from its content service.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "documents");
const files = readdirSync(source).filter((name) => name.endsWith(".json")).sort();

const entries = files.map((file) => {
  const name = file.replace(/\.json$/, "");
  const text = readFileSync(join(source, file), "utf8").trimEnd();
  return `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`;
});

writeFileSync(
  join(root, "src", "documents.generated.ts"),
  `// Generated by scripts/bundle-documents.mjs from documents/*.json.
// Do not edit; run \`npm run documents\` after changing a document.

export const DOCUMENTS = {
${entries.join("\n")}
} as const satisfies Readonly<Record<string, string>>;

/** The bundled document names, as a union: a typo is a compile error. */
export type DocumentName = keyof typeof DOCUMENTS;
`,
);
console.log(`bundled ${files.length} documents`);
